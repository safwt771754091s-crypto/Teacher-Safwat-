    public function run(): void
    {
        $written = 0;
        $figures = 0;

        foreach ($this->books() as $subject => $lessons) {
            $textbook = Textbook::where('title', 'like', "%{$subject}%")
                ->where('title', 'like', '%الثالث الثانوي%')
                ->first();

            if (! $textbook) {
                $this->command?->warn("No Grade 12 textbook found for «{$subject}».");

                continue;
            }

            foreach ($lessons as $title => $lesson) {
                $model = Lesson::where('textbook_id', $textbook->id)->where('title', $title)->first();

                if (! $model) {
                    continue;
                }

                // Replace the outline prose; leave any figure in place.
                LessonSection::where('lesson_id', $model->id)
                    ->whereNull('visual')
                    ->delete();

                $order = 0;
                LessonSection::create([
                    'lesson_id' => $model->id,
                    'type' => 'note',
                    'content' => $lesson['intro'],
                    'is_from_textbook' => false,
                    'sort_order' => $order++,
                ]);

                foreach ($lesson['points'] as $point) {
                    LessonSection::create([
                        'lesson_id' => $model->id,
                        'type' => $point[2] ?? 'point',
                        'title' => $point[0],
                        'content' => $point[1],
                        'is_from_textbook' => false,
                        'sort_order' => $order++,
                    ]);
                }

                LessonSection::create([
                    'lesson_id' => $model->id,
                    'type' => 'example',
                    'title' => 'مثال محلول',
                    'content' => $lesson['example'],
                    'is_from_textbook' => false,
                    'sort_order' => $order++,
                ]);

                $written++;

                if (! empty($lesson['model']) && ! $model->sections()->whereNotNull('visual')->exists()) {
                    LessonSection::create([
                        'lesson_id' => $model->id,
                        'type' => 'example',
                        'title' => 'نموذج علمي: '.$lesson['model']['title'],
                        'content' => $lesson['model']['caption'],
                        'visual' => $lesson['model']['spec'],
                        'is_from_textbook' => false,
                        'sort_order' => 900,
                    ]);
                    $figures++;
                }
            }

            // Scaffolding lessons (مقدمة، تقويم …) have no topic of their own, so
            // they get a map of the book's real topics instead of a blank page.
            foreach (Lesson::where('textbook_id', $textbook->id)
                ->whereIn('title', self::SCAFFOLDING_TITLES)->get() as $lesson) {
                if ($lesson->sections()->whereNotNull('visual')->exists()) {
                    continue;
                }
                $map = self::unitMap($textbook, $lesson, 'خريطة') ?? self::contentMap($lesson, 'خطوات');
                if (! $map) {
                    continue;
                }
                LessonSection::create([
                    'lesson_id' => $lesson->id,
                    'type' => 'example',
                    'title' => $map['title'],
                    'content' => $map['caption'],
                    'visual' => $map['spec'],
                    'is_from_textbook' => false,
                    'sort_order' => 900,
                ]);
                $figures++;
            }
        }

        $this->command?->info("Grade 12 content: {$written} lessons written, {$figures} new figures.");
    }

