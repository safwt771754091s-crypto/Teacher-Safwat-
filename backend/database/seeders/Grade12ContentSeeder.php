/**
 * Teaching content for Grade 12 (الصف الثالث الثانوي), all 13 books.
 *
 * The curriculum was seeded as an outline: every lesson carries a real title but
 * its body is the placeholder «نتعرف في هذا الدرس على…». This seeder replaces
 * that placeholder with a real explanation — a short introduction, the concepts
 * that must be understood, and a worked example.
 *
 * The text is written by us as teaching material. It is NOT a transcription of
 * the Yemeni edition, and nothing here claims to be: the sections are marked
 * `is_from_textbook = false`, so the lesson shows "شرح" rather than "نقاط من
 * الكتاب". When the official book text is imported it will sit beside this,
 * labelled as the textbook.
 *
 * Interactive models are owned by ScienceModelsSeeder. This seeder only adds a
 * figure for lessons that still have none, so the two never double up.
 */
class Grade12ContentSeeder extends Seeder
