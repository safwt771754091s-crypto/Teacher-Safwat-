    /**
     * A unit map for the scaffolding lessons (مقدمة، تمهيد، تقويم …): a sequence
     * of the other lessons in the same book. The lesson titles are real, so the
     * map is factual, and it gives the learner an overview instead of a blank.
     */
    public static function unitMap(Textbook $textbook, Lesson $lesson, string $marker): ?array
    {
        $siblings = Lesson::where('textbook_id', $textbook->id)
            ->where('id', '!=', $lesson->id)
            ->whereNotIn('title', self::SCAFFOLDING_TITLES)
            ->orderBy('page_from')
            ->pluck('title')
            ->take(6)
            ->all();

        if (count($siblings) < 3) {
            return null;
        }

        return [
            'title' => $marker.': خريطة الوحدة',
            'caption' => 'رتب مواضيع الوحدة كما ترد في الكتاب.',
            'spec' => [
                'kind' => 'sequence',
                'params' => ['prompt' => 'رتب مواضيع الوحدة.', 'steps' => $siblings],
                'prompt' => 'خريطة تبين مواضيع الوحدة وترتيبها.',
            ],
        ];
    }

    /**
     * A map built from the lesson's own content: the concepts it teaches, in the
     * order they are presented. Used for the scaffolding lessons of the general
     * subjects, where the book's other lessons are mostly scaffolding too, so
     * there are not enough real topics to build a unit map from.
     */
    public static function contentMap(Lesson $lesson, string $marker): ?array
    {
        $steps = LessonSection::where('lesson_id', $lesson->id)
            ->whereNotNull('title')
            ->where('title', 'not like', $marker.'%')
            ->where('type', '!=', 'note')
            ->orderBy('sort_order')
            ->pluck('title')
            ->take(6)
            ->all();

        if (count($steps) < 3) {
            return null;
        }

        return [
            'title' => $marker.': '.$lesson->title,
            'caption' => 'رتب عناصر الدرس كما وردت في الشرح.',
            'spec' => [
                'kind' => 'sequence',
                'params' => ['prompt' => 'رتب عناصر الدرس.', 'steps' => $steps],
                'prompt' => 'رتّب عناصر الدرس بالترتيب الصحيح.',
            ],
        ];
    }

