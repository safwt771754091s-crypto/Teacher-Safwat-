    private const MARKER = 'نموذج علمي';

    public function run(): void
    {
        $models = $this->models();
        // No status filter: a draft lesson is still about its topic, and the
        // model should be ready the moment the lesson is published.
        $lessons = Lesson::whereIn('title', array_keys($models))->get();

        $attached = 0;
        $touched = 0;

        foreach ($lessons as $lesson) {
            $specs = $models[$lesson->title] ?? [];
            if (! $specs) {
                continue;
            }
            $touched++;
            foreach ($specs as $i => $model) {
                LessonSection::updateOrCreate(
                    ['lesson_id' => $lesson->id, 'title' => self::MARKER.': '.$model['title']],
                    [
                        'type' => 'example',
                        'content' => $model['caption'],
                        'visual' => $model['spec'],
                        'is_from_textbook' => false,
                        'sort_order' => 900 + $i,
                    ],
                );
                $attached++;
            }
        }

        $this->command?->info("Science models attached: {$attached} across {$touched} lessons.");
    }

