/**
 * Interactive models for the science subjects and the remaining maths grades.
 *
 * Physics, chemistry, biology and maths (other than Grade 12) are seeded as
 * curriculum outlines: the lessons carry a real topic title — «الذرة»، «قوانين
 * نيوتن»، «نظرية فيثاغورس» — but their section text is still the placeholder.
 * The titles are genuine, so a model built for the topic is honest; the model's
 * labels are the standard names for the parts, and nothing claims to be quoted
 * from the Yemeni edition. Lessons whose title is a generic unit label («تمهيد»,
 * «مراجعة») are skipped: there is no topic to draw.
 *
 * Match is by lesson title across every grade that teaches it, so «التمثيل
 * البياني» in Grade 10 and in physics both get their figure.
 *
 * Idempotent: sections are matched on (lesson, title) and updated in place.
